const express = require('express');
const cors = require('cors');
const { Pool, types } = require('pg');

const app = express();

app.use(cors());
app.use(express.json({ limit: '1mb' }));

// Keep BIGINT IDs compatible with JavaScript numbers.
types.setTypeParser(20, value => Number(value));

if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL environment variable is missing');
}

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    max: 5,
    idleTimeoutMillis: 30000,
    // Managed free databases may need extra time to wake after inactivity.
    connectionTimeoutMillis: 60000
});

let databaseReady = false;
let databaseInitializationPromise = null;

// Permanently reserved author name: Swypyy.
// Blocks all capitalization variations and common invisible characters.
function isReservedAuthorName(value) {
    if (typeof value !== 'string') return false;

    return value
        .normalize('NFKC')
        .replace(/[\u200B-\u200D\uFEFF]/g, '')
        .trim()
        .toLowerCase() === 'swypyy';
}

// Initialize the schema on demand. Share an in-flight initialization attempt
// so simultaneous requests do not issue duplicate schema setup queries.
async function ensureDatabaseInitialized() {
    if (databaseReady) return;

    if (!databaseInitializationPromise) {
        databaseInitializationPromise = pool.query(`
            CREATE TABLE IF NOT EXISTS posts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                content TEXT NOT NULL,
                author TEXT NOT NULL DEFAULT 'Anonymous',
                date TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS comments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
                text TEXT NOT NULL,
                time TEXT NOT NULL
            );

            CREATE INDEX IF NOT EXISTS comments_post_id_idx
            ON comments(post_id);
        `).then(() => {
            databaseReady = true;
            console.log('Neon database connected and ready');
            console.log('Reserved author name protection enabled');
        }).finally(() => {
            databaseInitializationPromise = null;
        });
    }

    await databaseInitializationPromise;
}

// Keep the HTTP service available while a sleeping database wakes up. API
// requests wait for schema initialization and receive a useful retry response
// if the database is temporarily unavailable.
app.use('/api', async (req, res, next) => {
    try {
        await ensureDatabaseInitialized();
        next();
    } catch (error) {
        console.error('Database is not ready for API request:', error);
        res.status(503).json({
            error: 'The database is waking up. Please try again shortly.'
        });
    }
});

// Health check.
app.get('/healthz', async (req, res) => {
    try {
        await ensureDatabaseInitialized();
        await pool.query('SELECT 1');

        res.json({
            status: 'ok',
            database: 'connected',
            reservedNameProtection: 'enabled'
        });
    } catch (error) {
        console.error('Health check error:', error);

        res.status(503).json({
            status: 'error',
            database: 'waking or unavailable'
        });
    }
});

// Get all posts.
app.get('/api/posts', async (req, res) => {
    try {
        const result = await pool.query(`
            SELECT id, title, content, author, date
            FROM posts
            ORDER BY id DESC
        `);

        res.json(result.rows);
    } catch (error) {
        console.error('Get posts error:', error);

        res.status(500).json({
            error: 'Could not load posts'
        });
    }
});

// Create a post.
app.post('/api/posts', async (req, res) => {
    const { title, content, author } = req.body;

    // Block Swypyy for absolutely everyone.
    if (isReservedAuthorName(author)) {
        return res.status(400).json({
            error: 'The name Swypyy is reserved and cannot be used.'
        });
    }

    if (
        typeof title !== 'string' ||
        !title.trim() ||
        typeof content !== 'string' ||
        !content.trim()
    ) {
        return res.status(400).json({
            error: 'Title and content are required'
        });
    }

    try {
        const result = await pool.query(`
            INSERT INTO posts (title, content, author, date)
            VALUES ($1, $2, $3, $4)
            RETURNING id, title, content, author, date
        `, [
            title.trim(),
            content.trim(),
            typeof author === 'string' && author.trim()
                ? author.trim()
                : 'Anonymous',
            new Date().toLocaleDateString()
        ]);

        res.status(201).json({
            message: 'Post published successfully!',
            post: result.rows[0]
        });
    } catch (error) {
        console.error('Create post error:', error);

        res.status(500).json({
            error: 'Could not publish post'
        });
    }
});

// Get comments for a post.
app.get('/api/comments/:postId', async (req, res) => {
    try {
        const result = await pool.query(`
            SELECT id, text, time
            FROM comments
            WHERE post_id = $1
            ORDER BY id ASC
        `, [req.params.postId]);

        res.json(result.rows);
    } catch (error) {
        console.error('Get comments error:', error);

        res.status(500).json({
            error: 'Could not load comments'
        });
    }
});

// Add a comment.
app.post('/api/comments/:postId', async (req, res) => {
    const { text } = req.body;

    if (typeof text !== 'string' || !text.trim()) {
        return res.status(400).json({
            error: 'Comment text is required'
        });
    }

    try {
        const result = await pool.query(`
            INSERT INTO comments (post_id, text, time)
            VALUES ($1, $2, $3)
            RETURNING id, text, time
        `, [
            req.params.postId,
            text.trim(),
            new Date().toLocaleTimeString([], {
                hour: '2-digit',
                minute: '2-digit'
            })
        ]);

        res.status(201).json({
            message: 'Comment added successfully!',
            comment: result.rows[0]
        });
    } catch (error) {
        console.error('Add comment error:', error);

        if (error.code === '23503') {
            return res.status(404).json({
                error: 'Post not found'
            });
        }

        res.status(500).json({
            error: 'Could not add comment'
        });
    }
});

const PORT = process.env.PORT || 3000;

// Start listening before connecting to the database. On Render, a request can
// now reach the service and trigger the database to wake rather than causing
// the whole process to exit during cold-start initialization.
app.listen(PORT, () => {
    console.log(`Blog server listening on port ${PORT}`);
});

// Retry transient database startup failures with backoff instead of exiting.
async function initializeDatabaseInBackground() {
    let retryDelay = 5000;

    while (!databaseReady) {
        try {
            await ensureDatabaseInitialized();
        } catch (error) {
            console.error(
                `Database initialization failed; retrying in ${retryDelay / 1000}s:`,
                error
            );
            await new Promise(resolve => setTimeout(resolve, retryDelay));
            retryDelay = Math.min(retryDelay * 2, 60000);
        }
    }
}

initializeDatabaseInBackground();
